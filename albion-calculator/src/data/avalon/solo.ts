export const item = (
  slot: BuildItemSpec["slot"],
  baseId: string,
  opts: Partial<Pick<BuildItemSpec, "tier" | "enchant" | "label">> = {}
): BuildItemSpec => ({
  slot,
  baseId,
  tier: opts.tier ?? 4,
  enchant: opts.enchant ?? 0,
  ...(opts.label ? { label: opts.label } : {}),
});

