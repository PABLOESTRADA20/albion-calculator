const roleBuild = (
  id: string,
  kind: Build["kind"],
  name: string,
  role: string,
  roleType: Build["roleType"],
  groupSize: number,
  difficulty: 1 | 2 | 3 | 4,
  description: string,
  pros: string[],
  cons: string[],
  items: BuildItemSpec[],
  scores: { pve: number; pvp: number; mobility: number; survivability: number },
  tierRecommendation: string
): Build => ({
  id: `avalon-${id}`,
  avalon: true,
  mode: "pve",
  category: kind === "healer" ? "Group" : "Group",
  kind,
  activity: kind === "healer" ? "pve" : "pvp",
  groupSize,
  name,
  role,
  roleType,
  difficulty,
  description,
  pros,
  cons,
  items,
  scores,
  tierRecommendation,
});

